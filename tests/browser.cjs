const {chromium}=require('playwright');
const fs=require('fs');
if (!process.env.PARENTS_TEST_DATA) throw Error('Set PARENTS_TEST_DATA to a temporary test data directory');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:1000}});
 const failures=[];
 page.on('pageerror',e=>failures.push(e.message));
 const credentials=JSON.parse(fs.readFileSync(process.env.PARENTS_TEST_DATA+'/credentials.json'));
 await page.goto('http://127.0.0.1:8765/local');
 await page.getByLabel('Access token',{exact:true}).fill(credentials.local);
 await page.getByRole('button',{name:'Open companion'}).click();
 await page.getByRole('heading',{name:'Your local controls'}).waitFor();
 await page.evaluate(async()=>{
   const session=await (await fetch('/api/session')).json();
   await fetch('/api/synthetic/partial',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':session.csrf},body:JSON.stringify({id:crypto.randomUUID(),text:'A provisional synthetic phrase',generation:0})});
 });
 await page.getByText('A provisional synthetic phrase',{exact:true}).waitFor();
 if(await page.locator('.entry').count())throw Error('Partial became final history');
 await page.getByLabel('Add a fictional transcript').fill('<img src=x onerror="alert(1)"> Hello 世界');
 await page.getByRole('button',{name:'Save synthetic speech'}).click();
 await page.locator('.entry').filter({hasText:'Hello 世界'}).waitFor();
 if(await page.locator('.entry img').count())throw Error('HTML was rendered');
 await page.locator('.entry select').first().selectOption('handled');
 await page.getByRole('button',{name:'Mute listening',exact:true}).click();
 await page.getByRole('heading',{name:'Locally muted'}).waitFor();
 if(!await page.getByRole('button',{name:'Save synthetic speech'}).isDisabled())throw Error('Mute UI failed');
 await page.getByRole('button',{name:'Resume synthetic listening'}).click();
 await page.getByRole('heading',{name:'Synthetic input enabled'}).waitFor();
 await page.getByLabel('Search saved transcripts').fill('does not exist');
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await page.getByText('No matching transcripts.').waitFor();
 await page.getByLabel('Search saved transcripts').fill('');
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await page.locator('.entry').first().waitFor();
 await page.screenshot({path:(process.env.PARENTS_TEST_DATA+'/desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:(process.env.PARENTS_TEST_DATA+'/phone.png'),fullPage:true});
 // Real browser transport disconnect: saved history remains, stale state is visible.
 await page.context().setOffline(true);
 await page.getByText('○ Disconnected — history may be out of date').waitFor({timeout:15000});
 await page.context().setOffline(false);
 await page.getByText('● Connected to laptop').waitFor({timeout:20000});
 await page.reload();
 await page.locator('.entry').first().waitFor();
 if(await page.locator('.entry').count()!==1)throw Error('Duplicate history after reconnect');
 await page.getByRole('button',{name:'Sign out'}).click();
 await page.getByLabel('Access token',{exact:true}).fill(credentials.caregiver);
 await page.getByRole('button',{name:'Open companion'}).click();
 await page.getByText('Caregiver session',{exact:true}).waitFor();
 if(await page.locator('#local-controls').isVisible())throw Error('Caregiver local controls exposed');
 await page.getByLabel('Search saved transcripts').focus();
 await page.keyboard.press('Tab');
 if(await page.evaluate(()=>document.activeElement.textContent)!=='Search')throw Error('Keyboard search navigation failed');
 if(failures.length)throw Error(failures.join('\n'));
 console.log('PASS: browser sign-in, synthetic final text, safe HTML, acknowledgement, mute, search, mobile layout, offline/reconnect, reload deduplication, caregiver separation, keyboard focus; no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
